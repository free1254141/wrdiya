/**
 * دالة استرجاع نصائح واستشارات الاستثمار العقاري
 */
export function queryInvestmentIntelligence(query: string): InvestmentGuideTopic[] {
  const q = query.toLowerCase().trim();
  const results: InvestmentGuideTopic[] = [];

  for (const topic of Object.values(INVESTMENT_INTELLIGENCE_MAP)) {
    const matched =
      q.includes(topic.titleAr.toLowerCase()) ||
      q.includes(topic.category.toLowerCase()) ||
      topic.detailedAnalysis.some(p => p.toLowerCase().includes(q)) ||
      (q.includes('خصم') && topic.id.includes('cash')) ||
      (q.includes('كاش') && topic.id.includes('cash')) ||
      (q.includes('إيجار') && topic.id.includes('rental')) ||
      (q.includes('عائد') && topic.id.includes('rental')) ||
      (q.includes('أوفر') && topic.id.includes('overprice')) ||
      (q.includes('تأخير') && topic.id.includes('delay')) ||
      (q.includes('استلام') && topic.id.includes('delay')) ||
      (q.includes('تجاري') && topic.id.includes('commercial')) ||
      (q.includes('إداري') && topic.id.includes('commercial'));

    if (matched) {
      results.push(topic);
    }
  }

  if (results.length === 0 && (q.includes('استثمار') || q.includes('فلوس') || q.includes('مكسب') || q.includes('أرباح'))) {
    return [
      INVESTMENT_INTELLIGENCE_MAP['cash-discount-and-pv'],
      INVESTMENT_INTELLIGENCE_MAP['rental-yield-benchmarks'],
      INVESTMENT_INTELLIGENCE_MAP['commercial-operating-partners']
    ];
  }

  return results;
}
