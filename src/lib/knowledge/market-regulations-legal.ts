/**
 * دالة استرجاع ومطابقة الاستشارات القانونية بحسب استفسار العميل
 */
export function queryLegalIntelligence(query: string): LegalTopic[] {
  const q = query.toLowerCase().trim();
  const results: LegalTopic[] = [];

  for (const topic of Object.values(LEGAL_REGULATIONS_MAP)) {
    const matched =
      q.includes(topic.titleAr.toLowerCase()) ||
      q.includes(topic.titleEn.toLowerCase()) ||
      q.includes(topic.category.toLowerCase()) ||
      topic.detailedPoints.some(p => p.toLowerCase().includes(q)) ||
      (q.includes('تسجيل') && topic.id.includes('registration')) ||
      (q.includes('توكيل') && topic.id.includes('attorney')) ||
      (q.includes('تصالح') && topic.id.includes('reconciliation')) ||
      (q.includes('صيانة') && topic.id.includes('maintenance')) ||
      (q.includes('تنازل') && topic.id.includes('transfer')) ||
      (q.includes('ضريبة') && topic.id.includes('tax')) ||
      (q.includes('ملكية') && topic.id.includes('title')) ||
      (q.includes('روف') && topic.id.includes('reconciliation')) ||
      (q.includes('بدروم') && topic.id.includes('reconciliation'));

    if (matched) {
      results.push(topic);
    }
  }

  // إذا لم يتم مطابقة شيء محدد وكان السؤال قانوني عام، نرجع المواضيع الرئيسية
  if (results.length === 0 && (q.includes('قانون') || q.includes('عقد') || q.includes('ورق') || q.includes('شراء') || q.includes('أوراق'))) {
    return [
      LEGAL_REGULATIONS_MAP['property-registration-law9'],
      LEGAL_REGULATIONS_MAP['power-of-attorney-rules'],
      LEGAL_REGULATIONS_MAP['maintenance-deposit-rules']
    ];
  }

  return results;
}
