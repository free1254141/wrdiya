/**
 * دالة تطبيع النص العربي للبحث الذكي وتفادي الأخطاء الإملائية
 */
function normalizeArabicText(text: string): string {
  if (!text) return '';
  return text
    .toLowerCase()
    .trim()
    .replace(/[أإآ]/g, 'ا')
    .replace(/ة/g, 'ه')
    .replace(/ى/g, 'ي')
    .replace(/[\u064B-\u065F]/g, '') // حذف التشكيل
    .replace(/^(ال)/, '') // إزالة ال التعريف للبحث المرن
    .replace(/\s+/g, ' ');
}

