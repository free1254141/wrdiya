/**
 * مقارنة استثمارية ومعيشية دقيقة بين منطقتين
 */
export function compareTwoAreas(areaAQuery: string, areaBQuery: string): AreaComparisonResult | null {
  const intelA = getAreaIntelligence(areaAQuery);
  const intelB = getAreaIntelligence(areaBQuery);

  if (!intelA || !intelB) return null;

  const cashPriceDiffPct = Math.round(((intelA.avg_price_per_sqm_cash - intelB.avg_price_per_sqm_cash) / intelB.avg_price_per_sqm_cash) * 100);
  const installmentsPriceDiffPct = Math.round(((intelA.avg_price_per_sqm_installments - intelB.avg_price_per_sqm_installments) / intelB.avg_price_per_sqm_installments) * 100);

  let rentalYieldWinner: 'A' | 'B' | 'متطابقان' = 'متطابقان';
  if (intelA.expected_rental_yield_pct > intelB.expected_rental_yield_pct + 0.3) {
    rentalYieldWinner = 'A';
  } else if (intelB.expected_rental_yield_pct > intelA.expected_rental_yield_pct + 0.3) {
    rentalYieldWinner = 'B';
  }

  const horizonA = intelA.recommended_horizon_years;
  const horizonB = intelB.recommended_horizon_years;
  const investmentHorizonComparison = `أفق ${intelA.nameAr}: (${horizonA}) مقارنة بـ ${intelB.nameAr}: (${horizonB}).`;

  let summaryRecommendation = '';
  if (intelA.avg_price_per_sqm_cash > intelB.avg_price_per_sqm_cash) {
    summaryRecommendation = `منطقة (${intelA.nameAr}) أعلى تكلفة للدخول كاش بنسبة ${Math.abs(cashPriceDiffPct)}% من (${intelB.nameAr})، وتتميز بـ [${intelA.pros[0]}]. في المقابل، تتميز (${intelB.nameAr}) بأنها أكثر تنافسية في السعر وأسرع في العائد النقدي أو أطول في خطط التقسيط.`;
  } else {
    summaryRecommendation = `منطقة (${intelB.nameAr}) أعلى قيمة سوقية بنسبة ${Math.abs(cashPriceDiffPct)}% من (${intelA.nameAr}). تُعد (${intelA.nameAr}) الخيار الأكثر كفاءة مالية وتوفيراً للمتر، بينما توفر (${intelB.nameAr}) نمط حياة ووجاهة ومجتمعاً أكثر اكتمالاً.`;
  }

  return {
    areaA: intelA,
    areaB: intelB,
    cashPriceDiffPct,
    installmentsPriceDiffPct,
    rentalYieldWinner,
    investmentHorizonComparison,
    summaryRecommendation
  };
}

