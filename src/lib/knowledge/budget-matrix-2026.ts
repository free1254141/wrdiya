/**
 * دالة استخراج النصيحة والمشاريع حسب الميزانية ونوع الطلب لعام 2026/2027
 */
export function getBudgetRecommendations2026(
  budgetAmount: number,
  mode: 'cash' | 'down_payment' | 'both' = 'both'
): {
  tier: BudgetTier;
  summaryText: string;
} {
  const budget = Math.max(Number(budgetAmount) || 0, 300_000);
  const tier = BUDGET_TIERS_2026.find(t => budget >= t.minBudget && budget <= t.maxBudget) || BUDGET_TIERS_2026[BUDGET_TIERS_2026.length - 1];

  const formattedBudget = budget.toLocaleString('ar-EG');
  const lines: string[] = [
    `📊 **خريطة استثمار ميزانيتك (${formattedBudget} ج.م) في مصر 2026/2027:**`,
    `النطاق السعري: **${tier.labelAr}**`,
    '━━━━━━━━━━━━━━━━━━',
  ];

  if (mode === 'cash' || mode === 'both') {
    lines.push(
      '🟢 **1. خيار الشراء كاش واستلام فوري (بدون أقساط أو التزامات):**',
      `• **نوع الوحدات المتاحة:** ${tier.cashBuyingPower.unitTypes.join(' أو ')}`,
      `• **أبرز المناطق:** ${tier.cashBuyingPower.viableAreas.join('، ')}`,
      `• **أمثلة مشاريع حقيقية مطابقة:**\n  - ${tier.cashBuyingPower.concreteProjects.join('\n  - ')}`,
      `• **الميزة:** ${tier.cashBuyingPower.pros}`,
      `• **الملاحظة:** ${tier.cashBuyingPower.cons}`,
      ''
    );
  }

  if (mode === 'down_payment' || mode === 'both') {
    lines.push(
      '⚡ **2. خيار استخدام المبلغ كمقدم للشراء بالتقسيط (تعظيم القوة الشرائية):**',
      `• **القوة الشرائية التي يفتحها لك:** ${tier.downPaymentLeverage.maxPurchasingPower}`,
      `• **نوع الوحدات:** ${tier.downPaymentLeverage.unitTypes.join(' أو ')}`,
      `• **أبرز المناطق:** ${tier.downPaymentLeverage.viableAreas.join('، ')}`,
      `• **أمثلة مشاريع حقيقية مطابقة:**\n  - ${tier.downPaymentLeverage.concreteProjects.join('\n  - ')}`,
      `• **نظام السداد المعتاد:** ${tier.downPaymentLeverage.typicalInstallmentYears}`,
      `• **الميزة:** ${tier.downPaymentLeverage.pros}`,
      ''
    );
  }

  lines.push(
    '━━━━━━━━━━━━━━━━━━',
    `💡 **نصيحة سكنى بوت الصريحة:** ${tier.brokerAdvice2026}`
  );

  return {
    tier,
    summaryText: lines.join('\n')
  };
}
