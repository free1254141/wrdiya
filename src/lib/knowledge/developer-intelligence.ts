/**
 * مقارنة بين مطورين عقاريين
 */
export function compareTwoDevelopers(devAQuery: string, devBQuery: string): DeveloperComparisonResult | null {
  const devA = getDeveloperIntelligence(devAQuery);
  const devB = getDeveloperIntelligence(devBQuery);

  if (!devA || !devB) return null;

  let higherLiquidity: 'A' | 'B' | 'متكافئان' = 'متكافئان';
  if (devA.resale_liquidity_rating > devB.resale_liquidity_rating + 2) higherLiquidity = 'A';
  else if (devB.resale_liquidity_rating > devA.resale_liquidity_rating + 2) higherLiquidity = 'B';

  let betterMaintenance: 'A' | 'B' | 'متكافئان' = 'متكافئان';
  if (devA.finishing_and_maintenance_rating > devB.finishing_and_maintenance_rating + 2) betterMaintenance = 'A';
  else if (devB.finishing_and_maintenance_rating > devA.finishing_and_maintenance_rating + 2) betterMaintenance = 'B';

  let morePunctualDelivery: 'A' | 'B' | 'متكافئان' = 'متكافئان';
  if (devA.delivery_on_time_rating > devB.delivery_on_time_rating + 2) morePunctualDelivery = 'A';
  else if (devB.delivery_on_time_rating > devA.delivery_on_time_rating + 2) morePunctualDelivery = 'B';

  const overallBrokerVerdict = `مقارنة بين ${devA.nameAr} (${devA.tier}) و ${devB.nameAr} (${devB.tier}): يبرز ${higherLiquidity === 'A' ? devA.nameAr : devB.nameAr} في سهولة إعادة البيع والتسييل، بينما يقدم ${betterMaintenance === 'A' ? devA.nameAr : devB.nameAr} معايير متقدمة في الصيانة وجودة التشطيب.`;

  return {
    devA,
    devB,
    higherLiquidity,
    betterMaintenance,
    morePunctualDelivery,
    overallBrokerVerdict
  };
}

/**
 * استخراج قائمة كافة المطورين المتوفرين
 */
export function getAllDevelopersList(): { slug: string; nameAr: string; tier: DeveloperTier; score: number }[] {
  return Object.values(DEVELOPER_INTELLIGENCE_MAP).map(dev => ({
    slug: dev.slug,
    nameAr: dev.nameAr,
    tier: dev.tier,
    score: Math.round((dev.delivery_on_time_rating + dev.finishing_and_maintenance_rating + dev.resale_liquidity_rating) / 3)
  }));
}
