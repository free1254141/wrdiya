/**
 * دالة استرجاع بيانات المحاور والمواصلات وأثرها على العقار
 */
export function queryTransportIntelligence(query: string): TransportLine[] {
  const q = query.toLowerCase().trim();
  const results: TransportLine[] = [];

  for (const line of Object.values(TRANSPORT_INTELLIGENCE_MAP)) {
    const matched =
      q.includes(line.nameAr.toLowerCase()) ||
      q.includes(line.type.toLowerCase()) ||
      line.servicedAreas.some(a => q.includes(a.toLowerCase())) ||
      line.keyStationsOrIntersections.some(s => q.includes(s.toLowerCase())) ||
      (q.includes('مونوريل') && line.id.includes('monorail')) ||
      (q.includes('قطار') && (line.id.includes('lrt') || line.id.includes('high-speed'))) ||
      (q.includes('مواصلات') && line.type.includes('مونوريل')) ||
      (q.includes('محور') && line.id.includes('highways'));

    if (matched) {
      results.push(line);
    }
  }

  return results;
}
